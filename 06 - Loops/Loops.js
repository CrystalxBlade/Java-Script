// ==========================================
// JAVASCRIPT LOOPS
// ==========================================


// ==========================================
// 1. for LOOP
// ==========================================

for (let i = 1; i <= 5; i++) {
    console.log(i);
}


// ==========================================
// 2. for LOOP - Counting
// ==========================================

for (let i = 1; i <= 10; i++) {
    console.log("Number:", i);
}


// ==========================================
// 3. for LOOP - Reverse
// ==========================================

for (let i = 10; i >= 1; i--) {
    console.log(i);
}


// ==========================================
// 4. for LOOP - Even Numbers
// ==========================================

for (let i = 1; i <= 20; i++) {

    if (i % 2 === 0) {
        console.log("Even:", i);
    }

}


// ==========================================
// 5. for LOOP - Odd Numbers
// ==========================================

for (let i = 1; i <= 20; i++) {

    if (i % 2 !== 0) {
        console.log("Odd:", i);
    }

}


// ==========================================
// 6. while LOOP
// ==========================================

let count = 1;

while (count <= 5) {

    console.log(count);

    count++;
}


// ==========================================
// 7. while LOOP - Countdown
// ==========================================

let number = 5;

while (number >= 1) {

    console.log(number);

    number--;
}


// ==========================================
// 8. do...while LOOP
// ==========================================

let x = 1;

do {

    console.log(x);

    x++;

} while (x <= 5);


// ==========================================
// 9. do...while executes at least once
// ==========================================

let value = 10;

do {

    console.log("This runs once.");

    value++;

} while (value < 5);


// ==========================================
// 10. break
// ==========================================

for (let i = 1; i <= 10; i++) {

    if (i === 6) {
        break;
    }

    console.log(i);
}


// ==========================================
// 11. continue
// ==========================================

for (let i = 1; i <= 10; i++) {

    if (i === 5) {
        continue;
    }

    console.log(i);
}


// ==========================================
// 12. for...of
// ==========================================

let fruits = ["Apple", "Mango", "Banana"];

for (let fruit of fruits) {
    console.log(fruit);
}


// ==========================================
// 13. for...of with String
// ==========================================

let name = "Satish";

for (let character of name) {
    console.log(character);
}


// ==========================================
// 14. for...in
// ==========================================

let student = {
    name: "Blade",
    age: 24,
    city: "Noida"
};

for (let key in student) {

    console.log(key);
}


// ==========================================
// 15. for...in - Key and Value
// ==========================================

for (let key in student) {

    console.log(key + ":", student[key]);

}


// ==========================================
// 16. Nested Loops
// ==========================================

for (let i = 1; i <= 3; i++) {

    for (let j = 1; j <= 3; j++) {

        console.log("i =", i, "j =", j);

    }

}


// ==========================================
// 17. Multiplication Table
// ==========================================

let table = 5;

for (let i = 1; i <= 10; i++) {

    console.log(table + " x " + i + " = " + (table * i));

}


// ==========================================
// 18. Sum of Numbers
// ==========================================

let sum = 0;

for (let i = 1; i <= 10; i++) {

    sum += i;

}

console.log("Sum:", sum);


// ==========================================
// 19. Loop Through Array
// ==========================================

let numbers = [10, 20, 30, 40, 50];

for (let i = 0; i < numbers.length; i++) {

    console.log(numbers[i]);

}


// ==========================================
// 20. break in while Loop
// ==========================================

let i = 1;

while (i <= 10) {

    if (i === 6) {
        break;
    }

    console.log(i);

    i++;
}


// ==========================================
// 21. continue in while Loop
// ==========================================

let j = 0;

while (j < 10) {

    j++;

    if (j === 5) {
        continue;
    }

    console.log(j);
}